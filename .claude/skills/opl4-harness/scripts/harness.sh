#!/usr/bin/env bash
#  opl4-harness gate runner.  Every gate prints exactly one line "GATE <name> PASS|FAIL <detail>"
#  and the run ends with "HARNESS PASS" only if every requested gate passed.  A gate that cannot
#  build is a FAIL, never a skip.
#
#    harness.sh golden            PCM engine vs the golden model, all scenarios, bit-exact
#    harness.sh oracle            the golden model vs ref278 (openMSX port) + the SPEC section C flags
#    harness.sh load              heavy-load scenarios at long SDRAM latencies (current engine: FAIL, SPEC H4)
#    harness.sh mutants           every engine file in $MUT_DIR must FAIL golden (the harness can fail)
#    harness.sh stress            the current engine's MLAB register-file stress lockstep (run_stress.sh)
#    harness.sh memwr             fullsys R800 OTIR wave-memory upload + readback (mprobe_r), 0 errors
#    harness.sh cpuvis            CPU-visible lockstep vs the openMSX model (sim/cpuvis) + its mutants
#    harness.sh resource          ALM / warning-10999 gates from the last fit report
#    harness.sh all               oracle golden mutants cpuvis load resource (+ stress memwr if HEAVY=1)
#
#  env:
#    W         worktree (default: the worktree this skill is installed in)
#    ENGINE    the PCM engine file(s) under test, space separated (default: alu + eg_step + engine2)
#    MUT_DIR   directory of mutant engine files (*.sv), each a full replacement of the engine file
#              (default for ymf278_pcm_engine2.sv: generated by mutants/make_engine2_mutants.py)
#    SCEN      golden scenarios, "name:frames:model[:lats]" (g = golden_pcm.py, m = golden_pcm_memwr.py,
#              o = golden_pcm_omsx.py; lats "1/20" overrides LATS for that scenario)
#    LOAD_SCEN / LOAD_LATS   the load gate's scenarios / latencies
#    ORACLE_DEV   ref278 deviation flags the oracle gate applies (default: every SPEC section C flag)
#    CLK_HZ    engine clock for golden (default 128863620, the production clock: PIPE datapath)
#    LATS / MUT_LATS   SDRAM read latencies golden / mutants run at (default "1 20" / 1)
#    OUT       output root (default /data/_claude/tmp/opl4h)
#    REV       Quartus revision whose reports `resource` reads (default MSX1_V9968)
#    FIT_DIR   directory holding $REV.fit.rpt / $REV.map.rpt (default $W/output_files)
#    PCM_ALM_MAX / MS_ALM_MAX   budgets (default 1200 / 2500)
#    REGS      ymf278b_regs.sv to use in memwr (default the worktree's)
#    TOP       ymf278b_top.sv for cpuvis (default the worktree's); CPU_MUT_DIR its mutants
#    GEN       fullsys generated sources (sim/fullsys/prep.sh output).  Default: memwr runs
#              $W/sim/fullsys/prep.sh into its own output dir on every run.  A GEN outside $W is a
#              FAIL (gen/ is gitignored, so another tree's gen mixes that tree's ports and stubs in)
#    MEMWR_TAG output subdirectory name for memwr (default memwr), so a control can run beside it
set -u
export PATH=/home/linuxbrew/.linuxbrew/bin:$PATH
HERE0=$(cd "$(dirname "$0")" && pwd)
W=${W:-$(cd "$HERE0/../../../.." && pwd)}
export W
echo "harness: W=$W"
Y=$W/rtl/peripheral/SOUND/ymf278b_fpga
G=$Y/sim/golden
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-/data/_claude/tmp/opl4h}; mkdir -p "$OUT"
ENGINE=${ENGINE:-"$Y/rtl/pcm/ymf278_pcm_alu.sv $Y/rtl/pcm/ymf278_pcm_eg_step.sv $Y/rtl/pcm/ymf278_pcm_engine2.sv"}
REV=${REV:-MSX1_V9968}
PCM_ALM_MAX=${PCM_ALM_MAX:-1200}; MS_ALM_MAX=${MS_ALM_MAX:-2500}
#  Scenarios: <name>:<frames>:<model>.  model g = golden_pcm.py, m = golden_pcm_memwr.py (adds the
#  reg 03h-06h wave-memory writes), o = golden_pcm_omsx.py.  Override with SCEN="..." (same format).
#  The default model is o: golden_pcm.py + the wave-write position reset + reg 06h writes, which
#  the engine implements; on scenarios without those it is byte-identical to golden_pcm.py.
SCEN=${SCEN:-"sc_single8:900:o sc_square16:900:o sc_tri12_loop:1000:o sc_multi:1200:o sc_lfo:1500:o
  sc_pitchbend:1000:o sc_wavehi:800:o sc_odd16:900:o sc_relwave:300:o sc_dirdep_good:700:o
  sc_dirdep_bad:700:o sc_memhit:400:o sc_eg_dl:900:o sc_eg_damp:1000:o sc_tlramp:1000:o
  sc_lfo_reset:1500:o sc_pan_mix:1100:o sc_tblhdr:600:o sc_lfo_off:900:o sc_silence:900:o
  sc_memtype1:600:o
  sc_songchange24:800:o:1"}
#  24 voices, mass key-off / wave-number rewrite: bit-exact at lat 1, not at longer
#  latencies on the current engine (one header fetch per frame, SPEC H4)
LOAD_SCEN=${LOAD_SCEN:-"sc_songchange24:800:o"}
LOAD_LATS=${LOAD_LATS:-"6 10 20"}
ORACLE_DEV=${ORACLE_DEV:-"I1,I2,I4,I5,I7,I8,I9,I11"}
#  The production clock is 128.86 MHz, where the engine runs its PIPE datapath; 85.909 MHz runs
#  a different circuit.  LATS = SDRAM read latencies (tb +lat) every scenario runs at.
CLK_HZ=${CLK_HZ:-128863620}
LATS=${LATS:-"1 20"}
MUT_LATS=${MUT_LATS:-1}
ALL_OK=1
gate() { echo "GATE $1 $2 ${3:-}"; [ "$2" = PASS ] || ALL_OK=0; }

#  Reference streams, regenerated on every harness run (a cached stream can outlive the
#  scenario it was made from).
GOLD=$OUT/gold
#  gold_make uses SCEN/GOLD/GOLD_DONE as the caller sees them (do_load shadows all three)
gold_make() {
    [ -n "${GOLD_DONE:-}" ] && return 0
    rm -rf "$GOLD"; mkdir -p "$GOLD"
    (cd "$G" && python3 gen_pcm_testdata.py > "$GOLD/gen.log") || { echo "testdata generation failed"; return 1; }
    local e n f m
    for e in $SCEN; do
        IFS=: read -r n f m _ <<< "$e"
        case $m in g|m|o) ;; *) echo "scenario $n: unknown model '$m'"; return 1;; esac
        local py=golden_pcm.py; [ "$m" = m ] && py=golden_pcm_memwr.py; [ "$m" = o ] && py=golden_pcm_omsx.py
        (cd "$G" && python3 "$py" "$n.txt" mem.bin "$f" "$GOLD/$n.txt" > /dev/null) &
    done
    wait
    for e in $SCEN; do n=${e%%:*}; [ -s "$GOLD/$n.txt" ] || { echo "no reference for $n"; return 1; }; done
    GOLD_DONE=1
}

#  a scenario's own latency list ("1/20") wins over the run's, except in mutant runs (MUT_LATS)
scen_lats() { if [ -n "$1" ] && [ -z "${IN_MUT:-}" ]; then echo "${1//\// }"; else echo "$2"; fi; }

#  golden_run <tag> <lats> <engine files...>: 0 = every scenario at every latency bit-exact
#  (comparator lag 0, no off-by-1, no bad sample), 1 = mismatch, 2 = no binary
golden_run() {
    local tag=$1 lats=$2; shift 2
    local d="$OUT/golden_$tag"
    rm -rf "$d"; mkdir -p "$d/v" "$d/out"
    gold_make > "$d/why" || return 2
    verilator --binary --timing -Wno-fatal -Wno-WIDTH -Wno-UNOPTFLAT -Wno-TIMESCALEMOD \
       -Wno-DECLFILENAME -Wno-UNUSEDSIGNAL -Wno-CASEINCOMPLETE -Wno-BLKANDNBLK \
       -Wno-MULTIDRIVEN -Wno-PINMISSING -Wno-UNDRIVEN -Wno-SIDEEFFECT \
       -GCLK_HZ=$CLK_HZ --top-module tb_golden_pcm -o vgold -Mdir "$d/v" \
       "$@" "$Y/tb/tb_golden_pcm.sv" > "$d/build.log" 2>&1
    [ -x "$d/v/vgold" ] || { grep -m3 %Error "$d/build.log" > "$d/why"; return 2; }
    local e n f m sl lat
    for e in $SCEN; do
        IFS=: read -r n f m sl <<< "$e"
        for lat in $(scen_lats "$sl" "$lats"); do
            ( "$d/v/vgold" +script="$G/$n.txt" +mem="$G/mem.hex" +frames=$f +lat=$lat \
                  +out="$d/out/${n}_l$lat.txt" > "$d/out/${n}_l$lat.log" 2>&1
              python3 "$G/compare_pcm.py" "$d/out/${n}_l$lat.txt" "$GOLD/$n.txt" "$n@lat$lat" \
                  > "$d/out/${n}_l$lat.cmp" 2>&1 ) &
        done
    done
    wait
    local bad=0 c
    for e in $SCEN; do
        IFS=: read -r n f m sl <<< "$e"
        for lat in $(scen_lats "$sl" "$lats"); do
            c="$d/out/${n}_l$lat.cmp"
            #  strict: compare_pcm.py tolerates +-1 LSB and a +-2 frame lag; the gate does not
            if ! grep -qE "\(lag=0\): exact=[0-9]+ off-by-1=0 bad=0 maxd=0$" "$c" 2>/dev/null; then
                echo "$n@lat$lat: $(head -1 "$c" 2>/dev/null | sed 's/^\[[^]]*\] //')" >> "$d/why"; bad=1
            fi
        done
    done
    return $bad
}

do_golden() {
    local ns; ns=$(echo $SCEN | wc -w)
    golden_run eng "$LATS" $ENGINE; local r=$?
    local own; own=$(for e in $SCEN; do IFS=: read -r n f m sl <<< "$e"; [ -n "$sl" ] && printf '%s' " $n@{${sl//\// }}"; done)
    case $r in 0) gate golden PASS "$ns scenarios x lat {$LATS}${own:+ (except$own)} bit-exact at $CLK_HZ Hz ($OUT/golden_eng)";;
               2) gate golden FAIL "build: $(head -1 "$OUT/golden_eng/why")";;
               *) gate golden FAIL "$(head -3 "$OUT/golden_eng/why" | tr '\n' ';')";; esac
}

do_oracle() {
    #  The golden model is "openMSX + the SPEC section C deviations".  ref278 is a port of
    #  openMSX YMF278.cc; REF_OMSX=1 REF_DEV=<flags> adds those deviations one by one.
    #  PASS = with every flag on, ref278 equals the golden model on every scenario, and
    #  dropping any one flag changes at least one scenario (no flag is dead weight, and
    #  every deviation the model carries is named).
    local d="$OUT/oracle"; rm -rf "$d"; mkdir -p "$d"
    g++ -O2 -w -o "$d/ref278" "$G/ref278.cpp" 2> "$d/build.log" || { gate oracle FAIL "ref278 does not build"; return; }
    #  ORACLE_REF=<program> stands in for ref278 (to check the judge, e.g. one that crashes)
    [ -n "${ORACLE_REF:-}" ] && cp "$ORACLE_REF" "$d/ref278"
    gold_make > "$d/gold.log" || { gate oracle FAIL "no reference streams"; return; }
    local sets="all" x e n f m
    for x in ${ORACLE_DEV//,/ }; do sets="$sets no_$x"; done
    for x in $sets; do
        local dev=$ORACLE_DEV
        [ "$x" != all ] && dev=$(echo "${ORACLE_DEV//,/ }" | tr ' ' '\n' | grep -vx "${x#no_}" | paste -sd,)
        for e in $SCEN; do
            IFS=: read -r n f m _ <<< "$e"
            #  a ref278 that dies or writes a short stream is an error, never a "diff"
            #  (a crash in a no_<flag> run would otherwise count as "flag needed")
            ( cd "$G" && REF_OMSX=1 REF_DEV="$dev" "$d/ref278" mem.bin "$n.txt" "$f" "$d/${n}.$x" 2> "$d/${n}.$x.err"
              rc=$?
              if [ $rc != 0 ] || [ "$(wc -l < "$d/${n}.$x" 2>/dev/null)" != "$f" ] \
                 || [ "$(wc -l < "$GOLD/$n.txt" 2>/dev/null)" != "$f" ]; then echo "err rc=$rc"
              elif cmp -s "$d/${n}.$x" "$GOLD/$n.txt"; then echo same; else echo diff; fi > "$d/${n}.$x.r" ) &
        done
    done
    wait
    local bad="" dead="" hit errs
    errs=$(grep -l '^err' "$d"/*.r 2>/dev/null | wc -l)
    [ "$errs" = 0 ] || { gate oracle FAIL "$errs ref278 run(s) failed or wrote a short stream (see $d/*.err)"; return; }
    for e in $SCEN; do n=${e%%:*}; [ "$(cat "$d/$n.all.r" 2>/dev/null)" = same ] || bad="$bad $n"; done
    for x in ${ORACLE_DEV//,/ }; do
        hit=$(for e in $SCEN; do n=${e%%:*}; [ "$(cat "$d/$n.no_$x.r" 2>/dev/null)" = diff ] && echo "$n"; done | wc -l)
        echo "  oracle: without $x, $hit scenario(s) differ"
        [ "$hit" -gt 0 ] || dead="$dead $x"
    done
    local ns; ns=$(echo $SCEN | wc -w)
    if [ -z "$bad" ] && [ -z "$dead" ]; then
        gate oracle PASS "golden model == ref278 (openMSX) + {$ORACLE_DEV} on $ns scenarios; every flag needed"
    else
        gate oracle FAIL "differ:${bad:- none}; flags no scenario needs:${dead:- none}"
    fi
}

do_load() {
    #  Heavy load: 24 voices and a mass wave-number rewrite at realistic SDRAM latencies.
    #  The current engine FAILS here (SPEC H4); a new engine must not.
    local SCEN=$LOAD_SCEN GOLD=$OUT/gold_load GOLD_DONE=""
    local ns; ns=$(echo $SCEN | wc -w)
    golden_run load "$LOAD_LATS" $ENGINE; local r=$?
    case $r in 0) gate load PASS "$ns scenario(s) x lat {$LOAD_LATS} bit-exact ($OUT/golden_load)";;
               2) gate load FAIL "build: $(head -1 "$OUT/golden_load/why")";;
               *) gate load FAIL "$(head -3 "$OUT/golden_load/why" | tr '\n' ';')";; esac
}

do_mutants() {
    local last; last=$(echo $ENGINE | awk '{print $NF}')
    if [ -z "${MUT_DIR:-}" ] && [ "$(basename "$last")" = ymf278_pcm_engine2.sv ]; then
        #  the current engine: its mutants are generated from the file under test
        MUT_DIR=$OUT/mutants
        python3 "$HERE/../mutants/make_engine2_mutants.py" "$last" "$MUT_DIR" > /dev/null \
            || { gate mutants FAIL "mutant generation failed (an edit no longer matches the engine)"; return; }
    fi
    [ -n "${MUT_DIR:-}" ] && [ -d "$MUT_DIR" ] || { gate mutants FAIL "MUT_DIR not set or missing"; return; }
    gold_make > /dev/null || { gate mutants FAIL "no reference streams"; return; }
    local n=0 caught=0 m base others
    #  engine files other than the one a mutant replaces (the last file of ENGINE)
    others=$(echo $ENGINE | awk '{for(i=1;i<NF;i++) printf "%s ", $i}')
    for m in "$MUT_DIR"/*.sv; do
        [ -e "$m" ] || continue
        base=$(basename "$m" .sv)
        ( IN_MUT=1 golden_run "mut_$base" "$MUT_LATS" $others "$m"; echo $? > "$OUT/golden_mut_$base.rc" ) > /dev/null 2>&1 &
    done
    wait
    for m in "$MUT_DIR"/*.sv; do
        [ -e "$m" ] || continue
        n=$((n+1)); base=$(basename "$m" .sv)
        local r; r=$(cat "$OUT/golden_mut_$base.rc" 2>/dev/null || echo 2)
        if [ "$r" = 1 ]; then caught=$((caught+1))
            echo "  mutant $base: caught by $(cut -d: -f1 "$OUT/golden_mut_$base/why" | tr '\n' ' ')"
        elif [ "$r" = 2 ]; then echo "  mutant $base: DID NOT BUILD (not a valid mutant)"
        else echo "  mutant $base: NOT CAUGHT"; fi
    done
    [ $n -gt 0 ] && [ $caught -eq $n ] && gate mutants PASS "$caught/$n caught" || gate mutants FAIL "$caught/$n caught"
}

do_stress() {
    #  run_stress.sh wipes its OUT dir first, so its log lives beside it, not in it; it ends
    #  "PCM STRESS LOCKSTEP: PASS" or "RESULT FAIL: ..."
    local d="$OUT/stress" log="$OUT/stress.log"
    (cd "$Y/sim/lockstep" && OUT="$d" ./run_stress.sh) > "$log" 2>&1
    grep -q "^PCM STRESS LOCKSTEP: PASS" "$log" \
        && gate stress PASS "run_stress.sh quick: $(grep -m1 -E 'runs=' "$log" | sed 's/^ *//') (engine2 register file only)" \
        || gate stress FAIL "$(grep -m1 -E 'RESULT FAIL|FAIL:' "$log" | sed 's/^ *//') (see $log)"
}

do_memwr() {
    local d="$OUT/${MEMWR_TAG:-memwr}" tree_id=""; rm -rf "$d"; mkdir -p "$d"
    echo "  memwr: regs $(md5sum < "${REGS:-$Y/rtl/ymf278b_regs.sv}" | cut -c1-8) MEM_WRITE_DELAY=$(grep -oE 'MEM_WRITE_DELAY +=[ 0-9]+' "${REGS:-$Y/rtl/ymf278b_regs.sv}" | grep -oE '[0-9]+$')"
    cp "${REGS:-$Y/rtl/ymf278b_regs.sv}" "$d/ymf278b_regs.sv"
    #  MEMWR_LOG=<r800.log> judges an existing log instead of running (checks the judge itself)
    if [ -n "${MEMWR_LOG:-}" ]; then cp "$MEMWR_LOG" "$d/r800.log"
    else
        #  the generated sources must come from the tree under test: regenerate them here (4 s)
        #  unless GEN is given, and then it must live inside $W
        local gen="${GEN:-$d/gen}" rw rg
        if [ -n "${GEN:-}" ]; then
            rw=$(realpath "$W"); rg=$(realpath "$GEN")
            case "$rg/" in "$rw"/*) ;; *) gate memwr FAIL "GEN $rg is outside W $rw (another tree's generated sources)"; return;; esac
        else bash "$W/sim/fullsys/prep.sh" "$gen" > "$d/prep.log" 2>&1 || { gate memwr FAIL "prep.sh failed (see $d/prep.log)"; return; }
        fi
        #  every absolute path the build reads must be inside W or the gen dir
        local stray; stray=$(grep '^/' "$gen/filelist.txt" | while read -r f; do
            f=$(realpath "$f"); case "$f" in "$(realpath "$W")"/*|"$(realpath "$gen")"/*) ;; *) echo "$f";; esac; done)
        [ -z "$stray" ] || { gate memwr FAIL "filelist reads outside the tree: $(echo $stray)"; return; }
        GEN="$gen" PCM_ENGINE="$ENGINE" HEX="$HERE/../assets/mprobe_r.hex" LOG=r800.log bash "$HERE/../assets/run1.sh" "$d" > "$d/run1.out" 2>&1
        local cm; cm=$(git -C "$W" rev-parse --short HEAD); git -C "$W" diff --quiet HEAD || cm="$cm+dirty"
        tree_id="tree $cm, gen $(cd "$gen" && cat filelist.txt msx_ports.svh *.v *.sv sv/*.sv | md5sum | cut -c1-8)"
    fi
    #  only the per-phase lines count (the closing VPROBE summary repeats phase 7's count),
    #  and the probe must have reached its last phase with every checking phase reported
    local log="$d/r800.log" p miss=""
    grep -q "phase 15 at" "$log" || { gate memwr FAIL "probe did not reach phase 15 (see $d)"; return; }
    for p in 1 6 7 8 9; do grep -qE "phase $p errors [0-9]+" "$log" || miss="$miss $p"; done
    [ -z "$miss" ] || { gate memwr FAIL "no error count for phase(s)$miss (see $d)"; return; }
    local e; e=$(grep -hoE "phase [0-9]+ errors [0-9]+" "$log" | awk '{s+=$4} END {print s+0}')
    #  run1.sh swaps the filelist's PCM engine for ENGINE (PCM_ENGINE); say which engine,
    #  and say when the verdict is on a saved log
    local how="engine $(basename "$(echo $ENGINE | awk '{print $NF}')"), $tree_id"
    [ -n "${MEMWR_LOG:-}" ] && how="SAVED LOG $MEMWR_LOG, engine unknown"
    [ "$e" = 0 ] && gate memwr PASS "R800 OTIR 1024 B upload + readback, phases 1-15, 0 errors ($how)" \
                 || gate memwr FAIL "$e readback errors ($(grep -hoE "phase [0-9]+ errors [1-9][0-9]*" "$log" | tr '\n' ';'))"
}

do_cpuvis() {
    #  CPU-visible lockstep vs the openMSX model (sim/cpuvis): the tree must pass, every
    #  mutant (one CPU-visible edit in engine / regs / top) must fail
    local d="$OUT/cpuvis"; rm -rf "$d"; mkdir -p "$d"
    local last; last=$(echo $ENGINE | awk '{print $NF}')
    local others; others=$(echo $ENGINE | awk '{for(i=1;i<NF;i++) printf "%s ", $i}')
    local regs=${REGS:-$Y/rtl/ymf278b_regs.sv} top=${TOP:-$Y/rtl/ymf278b_top.sv}
    local md=${CPU_MUT_DIR:-}
    if [ -z "$md" ] && [ "$(basename "$last")" = ymf278_pcm_engine2.sv ]; then
        md=$d/mutants
        python3 "$HERE/../mutants/make_cpuvis_mutants.py" "$last" "$regs" "$top" "$md" > /dev/null \
            || { gate cpuvis FAIL "mutant generation failed (an anchor no longer matches)"; return; }
    fi
    ENGINE="$ENGINE" REGS="$regs" TOP="$top" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/tree" > "$d/tree.txt" 2>&1 &
    local m base tgt
    for m in "$md"/*.sv; do
        [ -e "$m" ] || continue
        base=$(basename "$m" .sv); tgt=${base##*__}
        case $tgt in
            engine) ENGINE="$others $m" REGS="$regs" TOP="$top" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/$base" > "$d/$base.txt" 2>&1 & ;;
            regs)   ENGINE="$ENGINE" REGS="$m" TOP="$top" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/$base" > "$d/$base.txt" 2>&1 & ;;
            top)    ENGINE="$ENGINE" REGS="$regs" TOP="$m" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/$base" > "$d/$base.txt" 2>&1 & ;;
        esac
    done
    wait
    local n=0 caught=0
    for m in "$md"/*.sv; do
        [ -e "$m" ] || continue
        n=$((n+1)); base=$(basename "$m" .sv)
        if grep -q "^CPUVIS FAIL: build" "$d/$base.txt"; then echo "  cpuvis mutant $base: DID NOT BUILD"
        elif grep -q "^CPUVIS FAIL" "$d/$base.txt"; then caught=$((caught+1))
            echo "  cpuvis mutant $base: caught ($(grep -m1 -E '^  BAD|not exercised' "$d/$base.txt" | sed 's/^ *//'))"
        else echo "  cpuvis mutant $base: NOT CAUGHT"; fi
    done
    local tl; tl=$(grep -m1 "^cpuvis:" "$d/tree.txt")
    #  a floor on what was judged: a model change that widens windows must not turn
    #  checks into "unjudged" passes (2026-10-24: 717 judged, 0 unjudged)
    local nj nu; nj=$(echo "$tl" | grep -oE '[0-9]+ checks' | grep -oE '[0-9]+'); nu=$(echo "$tl" | grep -oE '[0-9]+ unjudged' | grep -oE '[0-9]+')
    if [ "${nj:-0}" -lt "${CPUVIS_MIN_CHECKS:-717}" ] || [ "${nu:-999}" -gt "${CPUVIS_MAX_UNJUDGED:-0}" ]; then
        gate cpuvis FAIL "judged ${nj:-?} (min ${CPUVIS_MIN_CHECKS:-717}), unjudged ${nu:-?} (max ${CPUVIS_MAX_UNJUDGED:-0}): $tl"; return
    fi
    #  the count alone can be kept while checks are dropped or relabelled: the judged check
    #  keys ("op<n> <kind> <port> <check>") must equal the committed baseline.  A new engine
    #  whose ack timing moves windows changes them legitimately; then review the diff and
    #  commit a new baseline (CPUVIS_BASELINE points at another one).
    local bl=${CPUVIS_BASELINE:-$Y/sim/cpuvis/checks_baseline.txt} miss new
    [ -f "$d/tree/checks.txt" ] || { gate cpuvis FAIL "no checks.txt from the tree run: $tl"; return; }
    miss=$(comm -23 <(sort "$bl") <(sort "$d/tree/checks.txt") | wc -l)
    new=$(comm -13 <(sort "$bl") <(sort "$d/tree/checks.txt") | wc -l)
    if [ "$miss" != 0 ] || [ "$new" != 0 ]; then
        comm -3 <(sort "$bl") <(sort "$d/tree/checks.txt") > "$d/checks.diff"
        gate cpuvis FAIL "check set differs from $(basename "$bl"): $miss missing, $new new (see $d/checks.diff): $tl"; return
    fi
    if grep -q "^CPUVIS PASS" "$d/tree.txt" && [ $n -gt 0 ] && [ $caught -eq $n ]; then
        gate cpuvis PASS "$tl; check set == $(basename "$bl") ($(wc -l < "$bl")); mutants $caught/$n caught"
    else
        gate cpuvis FAIL "tree: $(grep -m1 '^CPUVIS' "$d/tree.txt") ${tl}; mutants $caught/$n caught"
    fi
}

do_resource() {
    #  ALMs exist only after fit (the map report has ALUTs): run a fit, map-only is not enough
    local rd=${FIT_DIR:-$W/output_files}
    local rpt="$rd/$REV.fit.rpt"
    echo "  resource: reading $rpt ($(date -r "$rpt" '+%F %T' 2>/dev/null))"
    [ -f "$rpt" ] || { gate resource FAIL "no fit report for $REV"; return; }
    [ -f "$rd/$REV.map.rpt" ] || { gate resource FAIL "no map report for $REV (warning 10999 cannot be counted)"; return; }
    #  the report must be newer than every MoonSound RTL file under test (mtime: a report
    #  from before an edit says nothing about the edit)
    local newer; newer=$(find "$Y/rtl" $ENGINE ${REGS:-} ${TOP:-} -name '*.sv' -newer "$rpt" 2>/dev/null | head -3 | tr '\n' ' ')
    [ -z "$newer" ] || { gate resource FAIL "fit report older than $newer"; return; }
    #  the PCM instance is u_pcm whatever its module is called, and that module must be the
    #  engine under test (a report of another engine proves nothing about this one)
    local ms pcm pmod want
    want=$(grep -m1 -oE '^\s*module\s+[A-Za-z0-9_]+' $(echo $ENGINE | awk '{print $NF}') | awk '{print $2}')
    ms=$(grep -E '^\s*;\s*\|ymf278b_top:u_moonsound\|?\s*;' "$rpt" | head -1 | awk -F';' '{split($3,a," "); print a[1]}')
    local pl; pl=$(grep -E '^\s*;\s*\|[A-Za-z0-9_]+:u_pcm\|?\s*;.*u_moonsound\|' "$rpt" | head -1)
    pcm=$(echo "$pl" | awk -F';' '{split($3,a," "); print a[1]}')
    pmod=$(echo "$pl" | sed -E 's/^\s*;\s*\|([A-Za-z0-9_]+):u_pcm.*/\1/')
    [ -n "$ms" ] || { gate resource FAIL "u_moonsound not found in $(basename "$rpt")"; return; }
    [[ "$pcm" =~ ^[0-9]+(\.[0-9]+)?$ ]] || { gate resource FAIL "u_pcm ALM count not found in $(basename "$rpt")"; return; }
    [ "$pmod" = "$want" ] || { gate resource FAIL "report's u_pcm is $pmod, the engine under test is $want"; return; }
    local w10999; w10999=$(grep -c "Warning (10999)" "$rd/$REV.map.rpt")
    local ok=1
    awk -v a="$pcm" -v b="$PCM_ALM_MAX" 'BEGIN{exit !(a<=b)}' || ok=0
    awk -v a="$ms"  -v b="$MS_ALM_MAX"  'BEGIN{exit !(a<=b)}' || ok=0
    [ "$w10999" = 0 ] || ok=0
    local ovr=""; [ "$PCM_ALM_MAX/$MS_ALM_MAX" = 1200/2500 ] || ovr=" BUDGET OVERRIDE (default 1200/2500)"
    #  resolved, so an output_files symlink into another tree is named too
    local rr; rr=$(realpath "$rpt")
    case "$rr" in "$(realpath "$W")"/*) ;; *) ovr="$ovr, report from $(dirname "$rr")";; esac
    #  ALMs only: whether that fit met timing is the Quartus gate's question, not this one
    [ $ok = 1 ] && gate resource PASS "PCM $pcm <= $PCM_ALM_MAX, MoonSound $ms <= $MS_ALM_MAX, 10999 x0 ($(basename "$rpt"); timing not judged)$ovr" \
                || gate resource FAIL "PCM $pcm (max $PCM_ALM_MAX), MoonSound $ms (max $MS_ALM_MAX), 10999 x$w10999 ($(basename "$rpt"))"
    echo "  RAM check: read the map report's RAM summary for every intended MLAB/M10K -- warnings alone are not proof"
}

