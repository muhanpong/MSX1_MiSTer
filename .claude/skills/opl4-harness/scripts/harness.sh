#!/usr/bin/env bash
#  opl4-harness gate runner.  Every gate prints exactly one line "GATE <name> PASS|FAIL <detail>"
#  and the run ends with "HARNESS PASS" only if every requested gate passed.  A gate that cannot
#  build is a FAIL, never a skip.
#
#    harness.sh golden            PCM engine vs the golden model, all scenarios, bit-exact
#    harness.sh mutants           every engine file in $MUT_DIR must FAIL golden (the harness can fail)
#    harness.sh stress            the current engine's MLAB register-file stress lockstep (run_stress.sh)
#    harness.sh memwr             fullsys R800 OTIR wave-memory upload + readback (mprobe_r), 0 errors
#    harness.sh cpuvis            CPU-visible lockstep vs the openMSX model (sim/cpuvis) + its mutants
#    harness.sh resource          ALM / warning-10999 gates from the last fit report
#    harness.sh all               golden mutants cpuvis resource (+ stress memwr if HEAVY=1)
#
#  env:
#    W         worktree (default: the worktree this skill is installed in)
#    ENGINE    the PCM engine file(s) under test, space separated (default: alu + eg_step + engine2)
#    MUT_DIR   directory of mutant engine files (*.sv), each a full replacement of the engine file
#              (default for ymf278_pcm_engine2.sv: generated by mutants/make_engine2_mutants.py)
#    SCEN      golden scenarios, "name:frames:model" (g = golden_pcm.py, m = golden_pcm_memwr.py, o = golden_pcm_omsx.py)
#    CLK_HZ    engine clock for golden (default 128863620, the production clock: PIPE datapath)
#    LATS / MUT_LATS   SDRAM read latencies golden / mutants run at (default "1 20" / 1)
#    OUT       output root (default /data/_claude/tmp/opl4h)
#    REV       Quartus revision whose reports `resource` reads (default MSX1_V9968)
#    FIT_DIR   directory holding $REV.fit.rpt / $REV.map.rpt (default $W/output_files)
#    PCM_ALM_MAX / MS_ALM_MAX   budgets (default 1200 / 2500)
#    REGS      ymf278b_regs.sv to use in memwr (default the worktree's)
#    TOP       ymf278b_top.sv for cpuvis (default the worktree's); CPU_MUT_DIR its mutants
#    GEN       fullsys generated sources (sim/fullsys/prep.sh output; default $W/sim/fullsys/gen)
#    MEMWR_TAG output subdirectory name for memwr (default memwr), so a control can run beside it
set -u
export PATH=/home/linuxbrew/.linuxbrew/bin:$PATH
HERE0=$(cd "$(dirname "$0")" && pwd)
W=${W:-$(cd "$HERE0/../../../.." && pwd)}
export W
echo "harness: W=$W"
Y=$W/rtl/peripheral/SOUND/ymf278b_fpga
G=$Y/sim/golden
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-/data/_claude/tmp/opl4h}; mkdir -p "$OUT"
ENGINE=${ENGINE:-"$Y/rtl/pcm/ymf278_pcm_alu.sv $Y/rtl/pcm/ymf278_pcm_eg_step.sv $Y/rtl/pcm/ymf278_pcm_engine2.sv"}
REV=${REV:-MSX1_V9968}
PCM_ALM_MAX=${PCM_ALM_MAX:-1200}; MS_ALM_MAX=${MS_ALM_MAX:-2500}
#  Scenarios: <name>:<frames>:<model>.  model g = golden_pcm.py, m = golden_pcm_memwr.py (adds the
#  reg 03h-06h wave-memory writes), o = golden_pcm_omsx.py.  Override with SCEN="..." (same format).
#  The default model is o: golden_pcm.py + the wave-write position reset + reg 06h writes, which
#  the engine implements; on scenarios without those it is byte-identical to golden_pcm.py.
SCEN=${SCEN:-"sc_single8:900:o sc_square16:900:o sc_tri12_loop:1000:o sc_multi:1200:o sc_lfo:1500:o
  sc_pitchbend:1000:o sc_wavehi:800:o sc_odd16:900:o sc_relwave:300:o sc_dirdep_good:700:o
  sc_dirdep_bad:700:o sc_memhit:400:o sc_eg_dl:900:o sc_eg_damp:1000:o sc_tlramp:1000:o
  sc_lfo_reset:1500:o sc_pan_mix:1100:o sc_tblhdr:600:o"}
#  The production clock is 128.86 MHz, where the engine runs its PIPE datapath; 85.909 MHz runs
#  a different circuit.  LATS = SDRAM read latencies (tb +lat) every scenario runs at.
CLK_HZ=${CLK_HZ:-128863620}
LATS=${LATS:-"1 20"}
MUT_LATS=${MUT_LATS:-1}
ALL_OK=1
gate() { echo "GATE $1 $2 ${3:-}"; [ "$2" = PASS ] || ALL_OK=0; }

#  Reference streams, regenerated on every harness run (a cached stream can outlive the
#  scenario it was made from).
GOLD=$OUT/gold
gold_make() {
    [ -n "${GOLD_DONE:-}" ] && return 0
    rm -rf "$GOLD"; mkdir -p "$GOLD"
    (cd "$G" && python3 gen_pcm_testdata.py > "$GOLD/gen.log") || { echo "testdata generation failed"; return 1; }
    local e n f m
    for e in $SCEN; do
        IFS=: read -r n f m <<< "$e"
        local py=golden_pcm.py; [ "$m" = m ] && py=golden_pcm_memwr.py; [ "$m" = o ] && py=golden_pcm_omsx.py
        (cd "$G" && python3 "$py" "$n.txt" mem.bin "$f" "$GOLD/$n.txt" > /dev/null) &
    done
    wait
    for e in $SCEN; do n=${e%%:*}; [ -s "$GOLD/$n.txt" ] || { echo "no reference for $n"; return 1; }; done
    GOLD_DONE=1
}

#  golden_run <tag> <lats> <engine files...>: 0 = every scenario at every latency bit-exact
#  (comparator lag 0, no off-by-1, no bad sample), 1 = mismatch, 2 = no binary
golden_run() {
    local tag=$1 lats=$2; shift 2
    local d="$OUT/golden_$tag"
    rm -rf "$d"; mkdir -p "$d/v" "$d/out"
    gold_make > "$d/why" || return 2
    verilator --binary --timing -Wno-fatal -Wno-WIDTH -Wno-UNOPTFLAT -Wno-TIMESCALEMOD \
       -Wno-DECLFILENAME -Wno-UNUSEDSIGNAL -Wno-CASEINCOMPLETE -Wno-BLKANDNBLK \
       -Wno-MULTIDRIVEN -Wno-PINMISSING -Wno-UNDRIVEN -Wno-SIDEEFFECT \
       -GCLK_HZ=$CLK_HZ --top-module tb_golden_pcm -o vgold -Mdir "$d/v" \
       "$@" "$Y/tb/tb_golden_pcm.sv" > "$d/build.log" 2>&1
    [ -x "$d/v/vgold" ] || { grep -m3 %Error "$d/build.log" > "$d/why"; return 2; }
    local e n f m lat
    for e in $SCEN; do
        IFS=: read -r n f m <<< "$e"
        for lat in $lats; do
            ( "$d/v/vgold" +script="$G/$n.txt" +mem="$G/mem.hex" +frames=$f +lat=$lat \
                  +out="$d/out/${n}_l$lat.txt" > "$d/out/${n}_l$lat.log" 2>&1
              python3 "$G/compare_pcm.py" "$d/out/${n}_l$lat.txt" "$GOLD/$n.txt" "$n@lat$lat" \
                  > "$d/out/${n}_l$lat.cmp" 2>&1 ) &
        done
    done
    wait
    local bad=0 c
    for e in $SCEN; do
        n=${e%%:*}
        for lat in $lats; do
            c="$d/out/${n}_l$lat.cmp"
            #  strict: compare_pcm.py tolerates +-1 LSB and a +-2 frame lag; the gate does not
            if ! grep -qE "\(lag=0\): exact=[0-9]+ off-by-1=0 bad=0 maxd=0$" "$c" 2>/dev/null; then
                echo "$n@lat$lat: $(head -1 "$c" 2>/dev/null | sed 's/^\[[^]]*\] //')" >> "$d/why"; bad=1
            fi
        done
    done
    return $bad
}

do_golden() {
    local ns; ns=$(echo $SCEN | wc -w)
    golden_run eng "$LATS" $ENGINE; local r=$?
    case $r in 0) gate golden PASS "$ns scenarios x lat {$LATS} bit-exact at $CLK_HZ Hz ($OUT/golden_eng)";;
               2) gate golden FAIL "build: $(head -1 "$OUT/golden_eng/why")";;
               *) gate golden FAIL "$(head -3 "$OUT/golden_eng/why" | tr '\n' ';')";; esac
}

do_mutants() {
    local last; last=$(echo $ENGINE | awk '{print $NF}')
    if [ -z "${MUT_DIR:-}" ] && [ "$(basename "$last")" = ymf278_pcm_engine2.sv ]; then
        #  the current engine: its mutants are generated from the file under test
        MUT_DIR=$OUT/mutants
        python3 "$HERE/../mutants/make_engine2_mutants.py" "$last" "$MUT_DIR" > /dev/null \
            || { gate mutants FAIL "mutant generation failed (an edit no longer matches the engine)"; return; }
    fi
    [ -n "${MUT_DIR:-}" ] && [ -d "$MUT_DIR" ] || { gate mutants FAIL "MUT_DIR not set or missing"; return; }
    gold_make > /dev/null || { gate mutants FAIL "no reference streams"; return; }
    local n=0 caught=0 m base others
    #  engine files other than the one a mutant replaces (the last file of ENGINE)
    others=$(echo $ENGINE | awk '{for(i=1;i<NF;i++) printf "%s ", $i}')
    for m in "$MUT_DIR"/*.sv; do
        [ -e "$m" ] || continue
        base=$(basename "$m" .sv)
        ( golden_run "mut_$base" "$MUT_LATS" $others "$m"; echo $? > "$OUT/golden_mut_$base.rc" ) > /dev/null 2>&1 &
    done
    wait
    for m in "$MUT_DIR"/*.sv; do
        [ -e "$m" ] || continue
        n=$((n+1)); base=$(basename "$m" .sv)
        local r; r=$(cat "$OUT/golden_mut_$base.rc" 2>/dev/null || echo 2)
        if [ "$r" = 1 ]; then caught=$((caught+1))
            echo "  mutant $base: caught by $(cut -d: -f1 "$OUT/golden_mut_$base/why" | tr '\n' ' ')"
        elif [ "$r" = 2 ]; then echo "  mutant $base: DID NOT BUILD (not a valid mutant)"
        else echo "  mutant $base: NOT CAUGHT"; fi
    done
    [ $n -gt 0 ] && [ $caught -eq $n ] && gate mutants PASS "$caught/$n caught" || gate mutants FAIL "$caught/$n caught"
}

do_stress() {
    #  run_stress.sh wipes its OUT dir first, so its log lives beside it, not in it; it ends
    #  "PCM STRESS LOCKSTEP: PASS" or "RESULT FAIL: ..."
    local d="$OUT/stress" log="$OUT/stress.log"
    (cd "$Y/sim/lockstep" && OUT="$d" ./run_stress.sh) > "$log" 2>&1
    grep -q "^PCM STRESS LOCKSTEP: PASS" "$log" \
        && gate stress PASS "run_stress.sh quick: $(grep -m1 -E 'runs=' "$log" | sed 's/^ *//') (engine2 register file only)" \
        || gate stress FAIL "$(grep -m1 -E 'RESULT FAIL|FAIL:' "$log" | sed 's/^ *//') (see $log)"
}

do_memwr() {
    local d="$OUT/${MEMWR_TAG:-memwr}"; rm -rf "$d"; mkdir -p "$d"
    echo "  memwr: regs $(md5sum < "${REGS:-$Y/rtl/ymf278b_regs.sv}" | cut -c1-8) MEM_WRITE_DELAY=$(grep -oE 'MEM_WRITE_DELAY +=[ 0-9]+' "${REGS:-$Y/rtl/ymf278b_regs.sv}" | grep -oE '[0-9]+$')"
    cp "${REGS:-$Y/rtl/ymf278b_regs.sv}" "$d/ymf278b_regs.sv"
    HEX="$HERE/../assets/mprobe_r.hex" LOG=r800.log bash "$HERE/../assets/run1.sh" "$d" > "$d/run1.out" 2>&1
    local e; e=$(grep -hoE "errors [0-9]+" "$d/r800.log" | awk '{s+=$2} END {print s+0}')
    grep -q "phase" "$d/r800.log" || { gate memwr FAIL "no probe output (see $d)"; return; }
    [ "$e" = 0 ] && gate memwr PASS "R800 OTIR 1024 B upload + readback, 0 errors" || gate memwr FAIL "$e readback errors"
}

do_cpuvis() {
    #  CPU-visible lockstep vs the openMSX model (sim/cpuvis): the tree must pass, every
    #  mutant (one CPU-visible edit in engine / regs / top) must fail
    local d="$OUT/cpuvis"; rm -rf "$d"; mkdir -p "$d"
    local last; last=$(echo $ENGINE | awk '{print $NF}')
    local others; others=$(echo $ENGINE | awk '{for(i=1;i<NF;i++) printf "%s ", $i}')
    local regs=${REGS:-$Y/rtl/ymf278b_regs.sv} top=${TOP:-$Y/rtl/ymf278b_top.sv}
    local md=${CPU_MUT_DIR:-}
    if [ -z "$md" ] && [ "$(basename "$last")" = ymf278_pcm_engine2.sv ]; then
        md=$d/mutants
        python3 "$HERE/../mutants/make_cpuvis_mutants.py" "$last" "$regs" "$top" "$md" > /dev/null \
            || { gate cpuvis FAIL "mutant generation failed (an anchor no longer matches)"; return; }
    fi
    ENGINE="$ENGINE" REGS="$regs" TOP="$top" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/tree" > "$d/tree.txt" 2>&1 &
    local m base tgt
    for m in "$md"/*.sv; do
        [ -e "$m" ] || continue
        base=$(basename "$m" .sv); tgt=${base##*__}
        case $tgt in
            engine) ENGINE="$others $m" REGS="$regs" TOP="$top" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/$base" > "$d/$base.txt" 2>&1 & ;;
            regs)   ENGINE="$ENGINE" REGS="$m" TOP="$top" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/$base" > "$d/$base.txt" 2>&1 & ;;
            top)    ENGINE="$ENGINE" REGS="$regs" TOP="$m" "$Y/sim/cpuvis/run_cpuvis.sh" "$d/$base" > "$d/$base.txt" 2>&1 & ;;
        esac
    done
    wait
    local n=0 caught=0
    for m in "$md"/*.sv; do
        [ -e "$m" ] || continue
        n=$((n+1)); base=$(basename "$m" .sv)
        if grep -q "^CPUVIS FAIL: build" "$d/$base.txt"; then echo "  cpuvis mutant $base: DID NOT BUILD"
        elif grep -q "^CPUVIS FAIL" "$d/$base.txt"; then caught=$((caught+1))
            echo "  cpuvis mutant $base: caught ($(grep -m1 -E '^  BAD|not exercised' "$d/$base.txt" | sed 's/^ *//'))"
        else echo "  cpuvis mutant $base: NOT CAUGHT"; fi
    done
    local tl; tl=$(grep -m1 "^cpuvis:" "$d/tree.txt")
    if grep -q "^CPUVIS PASS" "$d/tree.txt" && [ $n -gt 0 ] && [ $caught -eq $n ]; then
        gate cpuvis PASS "$tl; mutants $caught/$n caught"
    else
        gate cpuvis FAIL "tree: $(grep -m1 '^CPUVIS' "$d/tree.txt") ${tl}; mutants $caught/$n caught"
    fi
}

do_resource() {
    #  ALMs exist only after fit (the map report has ALUTs): run a fit, map-only is not enough
    local rd=${FIT_DIR:-$W/output_files}
    local rpt="$rd/$REV.fit.rpt"
    echo "  resource: reading $rpt ($(date -r "$rpt" '+%F %T' 2>/dev/null))"
    [ -f "$rpt" ] || { gate resource FAIL "no fit report for $REV"; return; }
    local ms pcm
    ms=$(grep -E '^\s*;\s*\|ymf278b_top:u_moonsound\|?\s*;' "$rpt" | head -1 | awk -F';' '{split($3,a," "); print a[1]}')
    pcm=$(grep -E '^\s*;\s*\|ymf278_pcm_engine2:u_pcm\|?\s*;' "$rpt" | head -1 | awk -F';' '{split($3,a," "); print a[1]}')
    [ -n "$ms" ] || { gate resource FAIL "u_moonsound not found in $(basename "$rpt")"; return; }
    local w10999; w10999=$(grep -c "Warning (10999)" "$rd/$REV.map.rpt" 2>/dev/null); w10999=${w10999:-0}
    local ok=1
    awk -v a="$pcm" -v b="$PCM_ALM_MAX" 'BEGIN{exit !(a<=b)}' || ok=0
    awk -v a="$ms"  -v b="$MS_ALM_MAX"  'BEGIN{exit !(a<=b)}' || ok=0
    [ "$w10999" = 0 ] || ok=0
    [ $ok = 1 ] && gate resource PASS "PCM $pcm <= $PCM_ALM_MAX, MoonSound $ms <= $MS_ALM_MAX, 10999 x0 ($(basename "$rpt"))" \
                || gate resource FAIL "PCM $pcm (max $PCM_ALM_MAX), MoonSound $ms (max $MS_ALM_MAX), 10999 x$w10999 ($(basename "$rpt"))"
    echo "  RAM check: read the map report's RAM summary for every intended MLAB/M10K -- warnings alone are not proof"
}

case "${1:-all}" in
    golden) do_golden;;
    mutants) do_mutants;;
    stress) do_stress;;
    memwr) do_memwr;;
    resource) do_resource;;
    cpuvis) do_cpuvis;;
    all) do_golden; do_mutants; do_cpuvis; do_resource; [ -n "${HEAVY:-}" ] && { do_stress; do_memwr; };;
    *) echo "usage: $0 golden|mutants|cpuvis|stress|memwr|resource|all"; exit 2;;
esac
[ $ALL_OK = 1 ] && echo "HARNESS PASS" || echo "HARNESS FAIL"
[ $ALL_OK = 1 ]
