#  Expected OUT log for multest.asm -- the R800 rules, independent of the RTL.
#  MULUB A,r : HL = A*r.  MULUW HL,ww : DE:HL = HL*ww, DE the high word.
#  Flags: S 0, Z result is zero, Y 0, H kept, X 0, P/V 0, N kept, C high half non-zero.
import sys
out = []
def o(port, val): out.append("O %02x %02x" % (port, val & 0xFF))
def flags(fpre, zero, carry):
    return (0 << 7) | (0x40 if zero else 0) | (0 << 5) | (fpre & 0x10) | (0 << 3) | (0 << 2) | (fpre & 0x02) | (1 if carry else 0)
def mulub(a, r, fpre):
    hl = a * r
    o(0x10, hl >> 8); o(0x11, hl & 0xFF)
    o(0x12, flags(fpre, hl == 0, (hl >> 8) != 0))
def muluw(hl, ww, fpre):
    res = hl * ww
    de = (res >> 16) & 0xFFFF
    lo = res & 0xFFFF
    o(0x13, de >> 8); o(0x14, de & 0xFF)
    o(0x10, lo >> 8); o(0x11, lo & 0xFF)
    o(0x12, flags(fpre, res == 0, de != 0))
for a, r, f in [(0x00,0x00,0x00),(0x01,0x01,0x00),(0x10,0x10,0x00),(0xFF,0xFF,0x00),
                (0x80,0x02,0xFF),(0x7F,0x01,0xFF),(0x00,0x5A,0xFF),
                (0x12,0x34,0x12),(0xFF,0x01,0x12),
                (0xA5,0x5A,0xED),(0x01,0xFF,0x00),(0x00,0x00,0xFF)]:
    mulub(a, r, f)
for hl, bc, f in [(0x0000,0x0000,0x00),(0x0001,0x0001,0x00),(0x1000,0x0010,0x00),
                  (0xFFFF,0xFFFF,0xFF),(0x8000,0x0002,0xFF),(0x00FF,0x0100,0x12),
                  (0x1234,0x0000,0xED)]:
    muluw(hl, bc, f)
muluw(0x1234, 0x0002, 0x12)
muluw(0xFFFF, 0x8000, 0xFF)
#  the two ED opcodes that must stay NOPs: HL untouched, F untouched (FF from the last case)
o(0x10, 0xBE); o(0x11, 0xEF); o(0x12, flags(0xFF, 0xFFFF*0x8000 == 0, ((0xFFFF*0x8000) >> 16) != 0))
print("\n".join(out))
