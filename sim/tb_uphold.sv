//  Is the OPL4 actually held in reset for the whole of an OSD upload?
//
//  MSX1.sv puts it plainly, above reset_ms: "keep the OPL4 in reset for the whole
//  transfer regardless of the toggle", because MoonSound runs on clk_sdram and would
//  otherwise keep issuing SDRAM ch4 traffic while memory_upload streams megabytes into
//  ch1 -- and a FW PACK upload moves pcm_rom_base under a live PCM fetch.  The comment
//  says this core has twice been bitten by sustained multi-channel SDRAM pressure.
//
//  But the hold is
//        upload_hold = reset_rq & status[64] & ~|flash16x_active
//  and flash16x_active (msx_slots.sv) is a SET-ONLY latch: a single cpu_mreq with an
//  ASCII16X or Yamanooto mapper sets it, and nothing clears it but `reset`.  It is
//  therefore still set when the NEXT upload starts, so upload_hold never rises -- and
//  with status[64] = 1 the `reset` term is not asserted either, since reset_raw takes
//  reset_rq only when ~status[64].
//
//  The checks below are written as the behaviour the comment asks for, so the ones
//  that fail are the hazard.  The DUT is generated by sim/mk_uphold_dut.py, which
//  lifts the latch and the reset chain verbatim out of the RTL.
`timescale 1ns/1ps
import MSX::*;

module tb_uphold;

   logic clk = 0;
   always #5 clk = ~clk;

   logic        RESET = 1'b0, reset_now = 1'b0, reset_rq = 1'b0;
   logic [63:0] status_hi = 64'd0;          // bit 0 carries status[64]
   mapper_typ_t mapper = MAPPER_NONE;
   logic        cpu_mreq = 1'b0, cart_num = 1'b0;
   logic  [1:0] flash16x_active;
   logic [26:0] flash16x_base[2];
   logic [15:0] flash16x_size[2];
   logic        reset, upload_hold, reset_ms;

   uphold_dut dut (
      .clk21m(clk), .RESET(RESET), .reset_now(reset_now), .reset_rq(reset_rq),
      .status_hi(status_hi), .mapper(mapper), .cpu_mreq(cpu_mreq), .cart_num(cart_num),
      .base_ram(27'h100000), .size(16'd512),
      .flash16x_active(flash16x_active), .flash16x_base(flash16x_base),
      .flash16x_size(flash16x_size),
      .o_reset(reset), .o_upload_hold(upload_hold), .o_reset_ms(reset_ms)
   );

   //  Two groups, because two separate fixes are in play.  HOLD is what fix (1) --
   //  deleting `& ~|flash16x_active` from upload_hold -- is responsible for.  S3 is
   //  the stale-base question, which is fix (2) and lives in MSX1.sv; it is expected
   //  to stay red here until that lands, and sim/run_staleflash.sh is its bench.
   int err_hold = 0, err_s3 = 0;
   task automatic ck(input string grp, input string what, input logic ok);
      if (!ok) begin
         if (grp == "S3") err_s3++; else err_hold++;
         $display("FAIL  %s", what);
      end else $display("ok    %s", what);
   endtask

   //  one CPU memory access through a mapper, the way the latch sees it
   task automatic touch_cart(input mapper_typ_t m, input logic num);
      @(negedge clk); mapper = m; cart_num = num; cpu_mreq = 1'b1;
      @(posedge clk);
      @(negedge clk); cpu_mreq = 1'b0; mapper = MAPPER_NONE;
      repeat (2) @(posedge clk);
   endtask

   //  hold reset_rq for `len` clk21m and count how many of those the OPL4 was held
   int held;
   task automatic upload(input int len);
      held = 0;
      @(negedge clk); reset_rq = 1'b1;
      for (int i = 0; i < len; i++) begin @(posedge clk); if (reset_ms) held++; end
      @(negedge clk); reset_rq = 1'b0;
      repeat (80) @(posedge clk);            // let the stretched reset expire
   endtask

   //  a real machine reset, then wait out the 63-cycle stretch
   task automatic machine_reset();
      @(negedge clk); RESET = 1'b1; repeat (4) @(posedge clk);
      @(negedge clk); RESET = 1'b0;
      repeat (80) @(posedge clk);
   endtask

   //  how long reset_ms stays asserted for a plain machine reset
   int ms_len;
   task automatic measure_reset_len();
      ms_len = 0;
      @(negedge clk); RESET = 1'b1; repeat (4) @(posedge clk);
      @(negedge clk); RESET = 1'b0;
      forever begin @(posedge clk); if (!reset_ms) break; ms_len++; end
   endtask

   localparam int UPLEN = 400;

   initial begin
      machine_reset();

      //  ---- the reset path, which is what v2b's 24-clk sweep depends on ----
      measure_reset_len();
      $display("  reset_ms for a machine reset: %0d clk21m (= %0d clk_sdram at 4x)",
               ms_len, ms_len*4);
      ck("HOLD", "R  a machine reset holds the OPL4 for >= 63 clk21m", ms_len >= 63);

      //  ---- T1: clean machine, the toggle set: the hold works --------------
      machine_reset();
      status_hi[0] = 1'b1;                   // status[64] = 1
      upload(UPLEN);
      $display("  T1 clean machine        : held %0d of %0d", held, UPLEN);
      ck("HOLD", "T1 the OPL4 is held for the whole transfer", held == UPLEN);

      //  ---- T2: one ASCII16X access first ----------------------------------
      machine_reset();
      status_hi[0] = 1'b1;
      touch_cart(MAPPER_ASCII16X, 1'b0);
      ck("HOLD", "T2a the flash latch is set by one ASCII16X access", flash16x_active != 2'b00);
      upload(UPLEN);
      $display("  T2 after ASCII16X access: held %0d of %0d  (latch=%b)",
               held, UPLEN, flash16x_active);
      ck("HOLD", "T2 the OPL4 is held for the whole transfer", held == UPLEN);
      $display("  T2b latch after the upload: %b base[0]=%x (set-only: only `reset` clears it)",
               flash16x_active, flash16x_base[0]);
      //  This is the S3 defect the guard in 042cc0d was written to prevent: the
      //  departed cart's base survives the swap and flash_dirtysave reads it live.
      //  `reset` clears flash16x_active but NOT base/size, and both save paths are
      //  gated on active (flash_dump_test.sv:72-73, flash_changelog.sv:100-101), so
      //  the property that matters is that a stale base cannot still be armed.
      ck("S3", "T2c a stale flash base is not left armed after the upload",
         flash16x_active == 2'b00 | flash16x_base[0] == 27'd0);

      //  ---- T3: Yamanooto does the same ------------------------------------
      machine_reset();
      status_hi[0] = 1'b1;
      touch_cart(MAPPER_YAMANOOTO, 1'b1);
      upload(UPLEN);
      $display("  T3 after Yamanooto      : held %0d of %0d", held, UPLEN);
      ck("HOLD", "T3 the OPL4 is held for the whole transfer", held == UPLEN);

      //  ---- T4: with the toggle clear, `reset` covers the upload ----------
      machine_reset();
      status_hi[0] = 1'b0;                   // status[64] = 0
      touch_cart(MAPPER_ASCII16X, 1'b0);
      upload(UPLEN);
      $display("  T4 toggle off           : held %0d of %0d (2 short = rst_meta sync)", held, UPLEN);
      //  reset_raw goes through two flops into clk21m, so the `reset` path costs two
      //  cycles at the start of the upload that upload_hold, being combinational,
      //  does not.  Two clk21m of live OPL4 at the very start of a transfer is not
      //  the hazard this bench is about.
      ck("HOLD", "T4 the OPL4 is held for the transfer, bar the 2-cycle sync", held >= UPLEN - 2);

      //  ---- T5: a machine reset restores the hold --------------------------
      machine_reset();
      status_hi[0] = 1'b1;
      touch_cart(MAPPER_ASCII16X, 1'b0);
      machine_reset();                       // clears the latch
      ck("HOLD", "T5a a machine reset clears the flash latch", flash16x_active == 2'b00);
      upload(UPLEN);
      $display("  T5 reset, then upload   : held %0d of %0d", held, UPLEN);
      ck("HOLD", "T5 the OPL4 is held for the whole transfer", held == UPLEN);

      $display("RESULT hold: %0d error(s)   <- fix (1), delete the term from upload_hold", err_hold);
      $display("RESULT s3:   %0d error(s)   <- fix (2), the per-cart restore gate (MSX1.sv)", err_s3);
      $display("RESULT: %0d error(s)", err_hold + err_s3);
      $finish;
   end

endmodule
