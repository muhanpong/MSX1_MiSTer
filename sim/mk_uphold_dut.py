#  Build the DUT for sim/tb_uphold.sv by EXTRACTING the two blocks under test
#  verbatim from the shipped RTL, so the bench tests the source and not a
#  re-typed copy of it.  Any edit that changes their shape makes this fail
#  loudly rather than silently testing something else.
import sys, os

slots = open('rtl/peripheral/slots/msx_slots.sv').read()
top   = open('MSX1.sv').read()

def take(text, first, last, what):
    i = text.find(first)
    if i < 0: sys.exit(f"mk_uphold_dut: anchor not found ({what}): {first!r}")
    j = text.find(last, i)
    if j < 0: sys.exit(f"mk_uphold_dut: end anchor not found ({what}): {last!r}")
    if text.find(first, i+1) >= 0: sys.exit(f"mk_uphold_dut: anchor not unique ({what})")
    return text[i:j+len(last)]

#  msx_slots.sv: the set-only flash16x_active latch
latch = take(slots,
   "always @(posedge clk) begin\n    if (reset) begin\n        flash16x_active <= 2'b00;",
   "end\nend", "flash16x_active latch")

#  MSX1.sv: upload_hold, the stretched machine reset, and reset_ms
uphold  = take(top, "wire upload_hold = reset_rq", ";", "upload_hold")
reset_ms= take(top, "wire reset_ms = reset", ";", "reset_ms")
rawline = take(top, "wire reset_raw = RESET", ";", "reset_raw")
stretch = take(top, "reg  [1:0] rst_meta", "wire reset = rst_meta[1] | (|rst_hold);", "reset stretch")

#  FIX=1 models fix (1): DELETE `& ~|flash16x_active` from upload_hold, so the CPU
#  pause and the OPL4 hold always work the way the toggle promises.  That is the fix
#  assigned to the audit session; T2/T3 go green and T2c stays red, because (1) makes
#  no claim about S3 -- that is fix (2), the per-cart gate on the restore decision,
#  which lives in MSX1.sv and is covered by sim/run_staleflash.sh.
#
#  NOT modelled any more: moving the term into reset_raw, so that a flash cart forces
#  the reset path.  It cleared this bench, but it makes an OSD load reset the machine
#  whenever a flash cart has been touched, which is what the toggle exists to avoid.
#  Rejected 2026-09-26, so it is gone rather than left here to be tried again.
#
#  Once (1) lands in MSX1.sv the term is gone from the source, so FIX=1 has nothing
#  left to model.  That is not an error: say so on stderr and extract as-is, and the
#  HOLD group should then be green with no flag at all.
#  BREAK=1 puts the term BACK, modelling the behaviour before a4541d9.  Without it this
#  bench has no way to go red on the HOLD group and cannot be shown to measure anything;
#  sim/checkrun.sh fails a bench whose outcome nothing can change.
if os.environ.get("BREAK") == "1":
    a = "wire upload_hold = reset_rq & status[64];"
    if a not in uphold: sys.exit("mk_uphold_dut: BREAK anchor moved (upload_hold)")
    uphold = "wire upload_hold = reset_rq & status[64] & ~|flash16x_active;"
    print("mk_uphold_dut: BREAK=1 -> term restored, pre-a4541d9 behaviour", file=sys.stderr)

TERM = " & ~|flash16x_active"
if TERM in uphold:
    if os.environ.get("FIX") == "1":
        uphold = uphold.replace(TERM, "")
        print("mk_uphold_dut: FIX=1 -> modelling fix (1), term deleted", file=sys.stderr)
elif os.environ.get("FIX") == "1":
    print("mk_uphold_dut: fix (1) is already in MSX1.sv; FIX=1 is a no-op",
          file=sys.stderr)

print(f"""//  GENERATED by sim/mk_uphold_dut.py -- do not edit.  The two blocks below are
//  lifted verbatim from rtl/peripheral/slots/msx_slots.sv and MSX1.sv.
`timescale 1ns/1ps
import MSX::*;

module uphold_dut
(
   input               clk21m,
   input               RESET,
   input               reset_now,
   input               reset_rq,
   input        [63:0] status_hi,      // status[64] as status_hi[0]
   input  mapper_typ_t mapper,
   input               cpu_mreq,
   input               cart_num,
   input        [26:0] base_ram,
   input        [15:0] size,
   output logic  [1:0] flash16x_active,
   output logic [26:0] flash16x_base[2],
   output logic [15:0] flash16x_size[2],
   output              o_reset,
   output              o_upload_hold,
   output              o_reset_ms
);
   wire clk = clk21m;
   wire [64:64] status = {{status_hi[0]}};

{latch}

{rawline}
{stretch}
{uphold}
{reset_ms}

   assign o_reset       = reset;
   assign o_upload_hold = upload_hold;
   assign o_reset_ms    = reset_ms;

endmodule""")
